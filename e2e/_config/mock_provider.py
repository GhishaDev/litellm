    def _count_prompt_chars_anthropic(self, body):
        try:
            n = 0
            system = body.get("system", "")
            if isinstance(system, str):
                n += len(system)
            elif isinstance(system, list):
                n += sum(len(b.get("text", "")) for b in system if isinstance(b, dict))
            for m in body.get("messages", []):
                c = m.get("content", "")
                if isinstance(c, str):
                    n += len(c)
                elif isinstance(c, list):
                    n += sum(len(b.get("text", "")) for b in c if isinstance(b, dict))
            return n
        except Exception:
            return 0

