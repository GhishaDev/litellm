    def _render_prometheus(self) -> str:
        """Render Stats as Prometheus text format. Stdlib-only, no prom client."""
        snap = STATS.snapshot()
        out = []
        out.append("# HELP mock_uptime_seconds Mock process uptime")
        out.append("# TYPE mock_uptime_seconds gauge")
        out.append(f"mock_uptime_seconds {snap['uptime_s']}")
        out.append("# HELP mock_in_flight_requests Current in-flight requests")
        out.append("# TYPE mock_in_flight_requests gauge")
        out.append(f"mock_in_flight_requests {snap['in_flight']}")
        out.append("# HELP mock_requests_total Requests by provider, mode, status")
        out.append("# TYPE mock_requests_total counter")
        for key, n in snap["requests"].items():
            try:
                provider, mode, status = key.split(":")
                out.append(
                    f'mock_requests_total{{provider="{provider}",mode="{mode}",status="{status}"}} {n}'
                )
            except ValueError:
                pass
        out.append("# HELP mock_chunks_total Streamed chunks by provider")
        out.append("# TYPE mock_chunks_total counter")
        for provider, n in snap["chunks"].items():
            out.append(f'mock_chunks_total{{provider="{provider}"}} {n}')
        out.append(
            "# HELP mock_errors_injected_total Forced/rate-injected failures by status"
        )
        out.append("# TYPE mock_errors_injected_total counter")
        for status, n in snap["errors_injected"].items():
            out.append(f'mock_errors_injected_total{{status="{status}"}} {n}')
        return "\n".join(out) + "\n"


