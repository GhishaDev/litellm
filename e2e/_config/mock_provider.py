    def _count_prompt_chars_gemini(self, body):
        """Gemini request shape: contents=[{role, parts:[{text|inline_data|file_data}]}], system_instruction:{parts:[...]}"""
        try:
            n = 0
            sysi = body.get("system_instruction") or body.get("systemInstruction") or {}
            for part in (sysi.get("parts") or []) if isinstance(sysi, dict) else []:
                if isinstance(part, dict):
                    n += len(part.get("text", "") or "")
            for c in body.get("contents", []):
                for part in c.get("parts", []) if isinstance(c, dict) else []:
                    if isinstance(part, dict):
                        n += len(part.get("text", "") or "")
                        # inline_data.data is base64 — count its length as bytes
                        idata = part.get("inline_data") or part.get("inlineData") or {}
                        n += len((idata or {}).get("data", "") or "")
            return n
        except Exception:
            return 0

